"""Regenerate docs/rules.md from skiniq/rules (run from the repo root)."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from skiniq.config import COLD_C, DRY_AIR_PCT, HOT_C, HUMID_PCT, UV_HIGH  # noqa: E402
from skiniq.rules import ALL_RULES  # noqa: E402

KBS = {
    "safety_medical": "Safety & Medical Constraint KB",
    "dermatological": "Dermatological KB",
    "ingredient_compatibility": "Ingredient & Chemical Compatibility KB",
    "environmental": "Environmental Adaptation KB",
}

lines = [
    "# Knowledge-base rules (proposal 3.6.3)", "",
    "Generated by `python tools/make_rules_doc.py` from `skiniq/rules/`. Every rule has a test in "
    "`tests/test_rules.py`, and every rule records its source.", "",
    "**Actions:** *exclude* removes the product; *caution* keeps it with a warning and a score penalty; "
    "*prefer* keeps it with a reason and a score bonus. Penalties and bonuses add up to each product's rule "
    "score, which the ranking (3.6.4) combines with TF-IDF similarity.", "",
    "Hard exclusions are used only for safety (pregnancy, ingredients the user avoids, medical skin conditions, "
    "harsh combinations for sensitive skin). The product dataset's `afterUse` tags come from an ingredient "
    "checker and fire on single ingredients (37% of products are tagged \"Acne Trigger\"), so they are used only "
    "as cautions or preferences.", "",
]
for kb, title in KBS.items():
    lines += [f"## {title}", "", "| Rule | Condition → action | Action | Weight | Source |", "|---|---|---|---:|---|"]
    for r in ALL_RULES:
        if r.kb == kb:
            w = f"{r.weight:+.2f}" if r.weight else "–"
            lines.append(f"| `{r.id}` | {r.description} | {r.action.value} | {w} | {r.source} |")
    lines.append("")

lines += [
    "## Routine-level compatibility checks", "",
    "`check_routine()` flags pairs of products in one routine: retinoid + AHA/BHA and two exfoliating "
    "products (Poelhekken & van der Bent, 2026), and hydroquinone + retinoid (Kim et al., 2017).", "",
    "Removed for weak evidence: vitamin C + AHA/BHA in one product, and vitamin C + retinoid in one routine.", "",
    "## Design choices (not from a source)", "",
    "| Item | Value | Note |", "|---|---|---|",
    "| Score weights | −0.25 to +0.30 | Heuristic; larger for direct concern/safety matches, smaller for weather |",
    f"| High UV | UV index ≥ {UV_HIGH:g} | WHO \"high\" category and above |",
    f"| Humid / dry air | ≥ {HUMID_PCT:g}% / < {DRY_AIR_PCT:g}% relative humidity | Design thresholds |",
    f"| Hot / cold | ≥ {HOT_C:g} °C / < {COLD_C:g} °C | Design thresholds |",
    "| Ingredient groups | `skiniq/products.py` | Citric acid is not an AHA (pH adjuster); carrier oils are not "
    "essential oils; fatty alcohols are not drying alcohol; bakuchiol is not a retinoid |", "",
    "## References", "",
    "### From the proposal's literature review", "",
    "Abhishek et al. (2023); Bialas et al. (2023); Hakulinen (2025); Kim et al. (2017); Lee & Lee (2025); "
    "Li et al. (2020); Narsa et al. (2024); Pavlou et al. (2021); Poelhekken & van der Bent (2026); "
    "Schachner et al. (2023); Suarantika et al. (2025); Vinardell (2015). Full entries: proposal reference list.", "",
    "### New references (add to the report's reference list)", "",
    "- Bozzo, P., Chua-Gocheco, A., & Einarson, A. (2011). Safety of skin care products during pregnancy. "
    "*Canadian Family Physician, 57*(6), 665–667. — Hydroquinone is substantially absorbed through the skin "
    "and best avoided in pregnancy; topical retinoids are advised against (case reports of birth defects with "
    "topical tretinoin).",
    "- Kaplan, Y. C., Ozsarfati, J., Etwel, F., Nickel, C., Nulman, I., & Koren, G. (2015). Pregnancy outcomes "
    "following first-trimester exposure to topical retinoids: a systematic review and meta-analysis. "
    "*British Journal of Dermatology, 173*(5), 1132–1141. — No significant rise in major malformations, but "
    "statistical power too low to justify use in pregnancy, so avoidance remains the precaution. "
    "**Verify the author list and pages on PubMed (PMID 26215715) before citing.**",
    "- U.S. Food and Drug Administration. (2005). *Guidance for industry: Labeling for topically applied "
    "cosmetic products containing alpha hydroxy acids as ingredients.* — AHAs increased UV sensitivity "
    "(sunburn) by about 18% after four weeks; recommends sunscreen during use and for a week after.",
    "- World Health Organization. (2002). *Global solar UV index: A practical guide.* WHO. — UV index "
    "categories: low 0–2, moderate 3–5, high 6–7, very high 8–10, extreme 11+. "
    "**Check these bands against the WHO PDF before citing.**",
    "",
    "The sun-sensitivity caution for retinoids follows the same FDA reasoning for AHAs; for a retinoid-"
    "specific source, check Bozzo et al. (2011) or a dermatology textbook.", "",
]
Path("docs/rules.md").write_text("\n".join(lines))
print(f"{len(ALL_RULES)} rules -> docs/rules.md")
