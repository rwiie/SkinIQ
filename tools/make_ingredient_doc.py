"""Regenerate docs/ingredients.md from data/knowledge/*.csv (run from the repo root)."""

import collections
import re
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from skiniq.products import (  # noqa: E402
    ALIASES_CSV, FUNCTIONS_CSV, PRODUCTS_CSV, clean_catalogue, ingredient_info, load_products, standardize,
)

aliases = pd.read_csv(ALIASES_CSV).fillna("")
table = pd.read_csv(FUNCTIONS_CSV).fillna("")
products = load_products()
raw = clean_catalogue(pd.read_csv(PRODUCTS_CSV))
raw_names = {p.strip() for s in raw.ingredients for p in re.split(r"(?<!\d),|,(?!\d)", s) if p.strip()}
std_names = {standardize(n) for n in raw_names}
occ = collections.Counter(i for p in products for i in p.ingredients)
mapped = sum(c for i, c in occ.items() if ingredient_info(i))
verify = (table.source.str.contains("verify")).sum()


def esc(s: str) -> str:
    return str(s).replace("|", "\\|")


lines = [
    "# Ingredient standardization and ingredient-function mapping (proposal 3.5.2)", "",
    "Generated by `python tools/make_ingredient_doc.py` from `data/knowledge/ingredient_aliases.csv` and "
    "`data/knowledge/ingredient_functions.csv`. Code: `skiniq/products.py`. Tests: `tests/test_ingredients.py`.", "",
    "## Results on the product catalogue", "",
    f"- Products: {len(products):,} Korean skincare products after cleaning.",
    f"- Distinct ingredient names: {len(raw_names):,} raw → {len(std_names):,} after standardization.",
    f"- Ingredient occurrences with a mapped function: {mapped:,} of {sum(occ.values()):,} "
    f"({mapped / sum(occ.values()):.0%}); products with at least one mapped function: "
    f"{sum(bool(p.functions) for p in products):,} of {len(products):,}.",
    "- Unmapped names are a long tail of plant extracts and minor ingredients, each used in few products.", "",
    "## Table 3.5.2.1: Ingredient standardization", "",
    "Each ingredient name is cleaned (whitespace, trailing `*`/`.`), stripped of concentrations "
    "(`Salicylic Acid 2%` → `Salicylic Acid`), and mapped to its INCI name when it is a common, EU or marketing "
    "name. Names in brackets are checked both ways (`Water (Aqua)` → `Water`). Duplicate names within one product "
    "are removed.", "",
    "| Raw ingredient variant | Standardized name (INCI) | Note |", "|---|---|---|",
    *[f"| {esc(r.variant)} | {esc(r.standard_name)} | {esc(r.note)} |" for r in aliases.itertuples()],
    "| *any name* + concentration, e.g. Niacinamide 5% | Niacinamide | Concentration removed |", "",
    "**Note:** on ingredient labels \"BHA\" is the INCI abbreviation of *butylated hydroxyanisole* (an antioxidant "
    "preservative), not beta hydroxy acid. In all 38 catalogue products that list it, it appears near the end of "
    "the list among minor additives (antioxidants, colourants, fragrance components), so it is not treated as an "
    "exfoliant.", "",
    "## Table 3.5.2.2: Ingredient-function mapping", "",
    "Each row matches ingredients by pattern. **Group** links the row to the knowledge-base rules (e.g. `retinoid`, "
    "`fragrance`); **Concerns** are the skin concerns the ingredient addresses, used by the ranking and the "
    "explanations.", "",
    "| Ingredient | Functions | Concerns addressed | Rule group | Source |", "|---|---|---|---|---|",
    *[f"| {esc(r.ingredient)} | {r.functions.replace('|', ', ').replace('_', ' ')} | "
      f"{r.concerns.replace('|', ', ').replace('_', ' ') or '–'} | {r.group or '–'} | {esc(r.source)} |"
      for r in table.itertuples()], "",
    f"**Sources:** rows citing the proposal's literature review are backed by it. {verify} rows marked "
    "*verify* (common cosmetic functions and ingredients not discussed in the proposal) should be checked against "
    "the EU CosIng database (https://ec.europa.eu/growth/tools-databases/cosing/) or a cosmetic chemistry reference "
    "before the report is final, or described as general cosmetic-science knowledge.", "",
]
Path("docs/ingredients.md").write_text("\n".join(lines))
print("docs/ingredients.md written")
