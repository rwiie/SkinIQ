"""Build the product photo gallery shown on GitHub (docs/gallery/).

One page per routine step (cleanser, toner, ...) with every product's photo in a grid,
its name, and a link to its INKEEDecoder page; products without a photo are listed at
the end of each page. Photos are the originals linked from
data/knowledge/product_images.csv (the app removes the background when it shows them).

Run from the repository root after the photo list changes:

    python tools/make_gallery.py
"""

from __future__ import annotations

import sys
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from skiniq.explain import STEP_LABELS  # noqa: E402
from skiniq.product_images import SOURCE_NAME, product_image  # noqa: E402
from skiniq.products import load_products  # noqa: E402

OUT = ROOT / "docs" / "gallery"
COLUMNS = 5
PHOTO_HEIGHT = 120
STEP_ORDER = ("cleanser", "toner", "treatment", "moisturizer", "sunscreen", "exfoliator", "mask")


def _cell(product, photo: dict) -> str:
    name = escape(product.title)
    return (f'<td align="center" valign="top" width="{100 // COLUMNS}%">'
            f'<a href="{escape(photo["page_url"], quote=True)}">'
            f'<img src="{escape(photo["image_url"], quote=True)}" height="{PHOTO_HEIGHT}" alt="{name}"></a>'
            f"<br><sub>{name}</sub></td>")


def step_page(step: str, products: list) -> tuple[str, int]:
    label = STEP_LABELS.get(step, step.title())
    with_photo = [(p, product_image(p.brand, p.name)) for p in products]
    shown = [(p, ph) for p, ph in with_photo if ph]
    missing = [p for p, ph in with_photo if not ph]
    lines = [f"# {label}", "",
             f"[All categories](README.md) · {len(shown)} of {len(products)} products have a photo. "
             f"Click a photo to open the product on {SOURCE_NAME}.", "", "<table>"]
    for i in range(0, len(shown), COLUMNS):
        row = "".join(_cell(p, ph) for p, ph in shown[i:i + COLUMNS])
        lines.append(f"<tr>{row}</tr>")
    lines.append("</table>")
    if missing:
        lines += ["", f"## Without a photo ({len(missing)})", "",
                  "Not on " + SOURCE_NAME + ", or no page there clearly names the same product.", ""]
        lines += [f"- {p.title}" for p in missing]
    return "\n".join(lines) + "\n", len(shown)


def main() -> None:
    products = sorted(load_products(), key=lambda p: (p.brand.lower(), p.name.lower()))
    by_step: dict[str, list] = {}
    for p in products:
        by_step.setdefault(p.step, []).append(p)
    steps = [s for s in STEP_ORDER if s in by_step] + sorted(set(by_step) - set(STEP_ORDER))

    OUT.mkdir(parents=True, exist_ok=True)
    rows, total_photos = [], 0
    for step in steps:
        page, n = step_page(step, by_step[step])
        (OUT / f"{step}.md").write_text(page, encoding="utf-8")
        total_photos += n
        rows.append(f"| [{STEP_LABELS.get(step, step.title())}]({step}.md) | {len(by_step[step])} | {n} |")

    index = [
        "# Product photo gallery", "",
        f"Photos of the {len(products)} catalogue products, from {SOURCE_NAME} (formerly INCIDecoder). "
        f"{total_photos} products ({total_photos / len(products):.0%}) have a photo; every match was checked "
        "against the name on the product's own page.", "",
        "These are the original photos. In the app and the PDF the background is removed and each product is "
        "trimmed and centred at the same size (`tidy_photo` in `skiniq/product_images.py`).", "",
        "| Category | Products | With photo |", "|---|---:|---:|", *rows, "",
        "Generated by `python tools/make_gallery.py` from `data/knowledge/product_images.csv`.", "",
    ]
    (OUT / "README.md").write_text("\n".join(index), encoding="utf-8")
    print(f"{len(steps)} pages, {total_photos} photos -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
